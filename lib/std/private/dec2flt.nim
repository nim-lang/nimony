# ── scanning ──────────────────────────────────────────────────────────────

template isDigit(c: char): bool = c >= '0' and c <= '9'

func takeSignificant(s: openArray[char]; digitsStart, digitsEnd: int):
    tuple[mantissa: uint64, exponent: int, manyDigits: bool] =
  ## More than 19 significant digits: keep the first 19, as Rust's parser
  ## re-reads them. The digit text holds digits, `_`s and at most one `.`.
  var mantissa = 0'u64
  var taken = 0
  var exponent = 0
  var many = false
  var seen = false
  var inFraction = false
  let start = max(digitsStart, 0)
  let stop = min(digitsEnd, s.len)
  for k in start ..< stop:
    let c = s[k]
    if c == '.':
      inFraction = true
    elif c != '_':
      let d = uint64(ord(c) - ord('0'))
      if seen or d != 0'u64:
        seen = true
        if taken < MaxMantissaDigits:
          mantissa = mantissa * 10'u64 + d
          inc taken
          if inFraction: dec exponent
        else:
          if not inFraction: inc exponent
          if d != 0'u64: many = true
      elif inFraction:
        dec exponent              # a leading zero after the point
  result = (mantissa: mantissa, exponent: exponent, manyDigits: many)

func readDigits(s: openArray[char]; start: int; mantissa: var uint64;
                count: var int): int {.
    requires: 0 <= start, ensures: 0 <= result.} =
  ## Reads a run of digits from `start` into `mantissa` (wrapping past 19 of
  ## them; the caller re-reads those), adds their number to `count` and
  ## returns where the run ends. Underscores after a digit are allowed and
  ## ignored, as in Nim's literals.
  var i = start
  while i < s.len and isDigit(s[i]):
    mantissa = mantissa * 10'u64 + uint64(ord(s[i]) - ord('0'))
    inc count
    inc i
    while i < s.len and s[i] == '_': inc i
  result = i

func scanNumber(s: openArray[char]; n: var Number): int =
  ## `[sign] digits ['.' [digits]] [('e'|'E') [sign] digits]`, or
  ## `[sign] '.' digits ...`, in one pass without per-digit bookkeeping, as
  ## Rust's `parse_partial_number`. Returns the length, 0 if there are no
  ## digits. An `e` without digits after it is not part of the number.
  var i = 0
  if i < s.len and (s[i] == '-' or s[i] == '+'):
    n.negative = s[i] == '-'
    inc i
  n.digitsStart = i
  var mantissa = 0'u64
  var digits = 0
  i = readDigits(s, i, mantissa, digits)
  var fraction = 0
  if i < s.len and s[i] == '.':
    inc i
    i = readDigits(s, i, mantissa, fraction)
    digits = digits + fraction
  n.digitsEnd = i
  if digits == 0:
    result = 0
  else:
    result = i
    var exponent = 0
    if i < s.len and (s[i] == 'e' or s[i] == 'E'):
      var j = i + 1
      var negative = false
      if j < s.len and (s[j] == '+' or s[j] == '-'):
        negative = s[j] == '-'
        inc j
      if j < s.len and isDigit(s[j]):
        while j < s.len and isDigit(s[j]):
          if exponent < ExpSaturation: exponent = exponent * 10 + (ord(s[j]) - ord('0'))
          inc j
          while j < s.len and s[j] == '_': inc j
        if negative: exponent = -exponent
        result = j
    n.explicitExp = exponent      # 0 unless an exponent was read
    if digits > MaxMantissaDigits:
      # Leading zeros are not significant: the wrapped-around accumulation
      # above is still exact if at most 19 digits follow them.
      let start = max(n.digitsStart, 0)
      let stop = min(n.digitsEnd, s.len)
      var k = start
      while k < stop and (s[k] == '0' or s[k] == '.' or s[k] == '_'):
        if s[k] == '0': dec digits
        inc k
    if digits <= MaxMantissaDigits:
      n.mantissa = mantissa
      n.exponent = n.explicitExp - fraction
    else:
      let taken = takeSignificant(s, n.digitsStart, n.digitsEnd)
      n.mantissa = taken.mantissa
      n.manyDigits = taken.manyDigits
      n.exponent = taken.exponent + n.explicitExp

func matchesIgnoreCase(s: openArray[char]; i: int; word: string): bool {.
    requires: i >= 0.} =
  result = i + word.len <= s.len
  for k in 0 ..< word.len:
    if result:
      let at = i + k
      {.assume: 0 <= at and at < s.len.}  # `i + word.len <= s.len` holds while `result` does
      let c = s[at]
      let lower = if c in {'A'..'Z'}: chr(ord(c) + (ord('a') - ord('A'))) else: c
      if lower != word[k]: result = false

func scanSpecial(s: openArray[char]; isNan, negative: var bool): int =
  ## `[sign] (nan | inf | infinity)`, case-insensitive, not followed by an
  ## identifier character. Returns the length, or 0.
  const IdentChars = {'a'..'z', 'A'..'Z', '0'..'9', '_'}
  var i = 0
  if i < s.len and (s[i] == '+' or s[i] == '-'):
    negative = s[i] == '-'
    inc i
  var len = 0
  if matchesIgnoreCase(s, i, "nan"):
    isNan = true
    len = 3
  elif matchesIgnoreCase(s, i, "infinity"):
    len = 8
  elif matchesIgnoreCase(s, i, "inf"):
    len = 3
  let after = i + len
  {.assume: 0 <= after.}
  if len > 0 and (after >= s.len or s[after] notin IdentChars):
    result = i + len
  else:
    result = 0

# ── Eisel–Lemire ──────────────────────────────────────────────────────────

proc clz64(x: uint64): int32 {.intrinsic: "Clz", noSideEffect.}

func leadingZeros(x: uint64): int =
  ## For x != 0 (the portable `Clz` intrinsic is undefined at 0).
  result = int(clz64(x))

func fullMulPortable(a, b: uint64; hi: var uint64): uint64 =
  ## The 128-bit product a*b: returns the low word, stores the high one.
  let aLo = a and 0xFFFFFFFF'u64
  let aHi = a shr 32
  let bLo = b and 0xFFFFFFFF'u64
  let bHi = b shr 32
  let b00 = aLo * bLo
  let b01 = aLo * bHi
  let b10 = aHi * bLo
  let b11 = aHi * bHi
  let mid1 = b10 + (b00 shr 32)
  let mid2 = b01 + (mid1 and 0xFFFFFFFF'u64)
  hi = b11 + (mid1 shr 32) + (mid2 shr 32)
  result = (b00 and 0xFFFFFFFF'u64) or (mid2 shl 32)

# On the native backend one `mul` replaces the four 32-bit products. x86-64
# only, as in `std/crypto`: AArch64's `.assembler` mode does not lower
# `mul3`/`umulh` yet.
# TODO: unlike `std/crypto` (`tests/nimony/crypto` in `NativeTestDirsX64`), no
# native test runs this path: `tests/nimony/stdlib/tparsefloat` is skipped
# natively until arkham's x86-64 float negation keeps the sign of zero. Add it
# to the native x86-64 suite once it passes there.
when defined(nimNativeBackend) and defined(amd64):
  type Words = ptr UncheckedArray[uint64]

  proc mulq(lo: var uint64; hi: var uint64; s: uint64) {.instruction: "mul".}

  proc fullMulAsm(a {.register: "rdi".}: uint64; b {.register: "rsi".}: uint64;
                  hiOut {.register: "rdx".}: Words): uint64 {.assembler.} =
    var dst {.register: "rcx".}: Words
    var lo {.register: "rax".}: uint64
    dst = hiOut                  # `mul` overwrites rdx
    var hi {.register: "rdx".}: uint64
    lo = a
    mulq(lo, hi, b)              # rdx:rax = rax * b
    dst[0] = hi
    result = lo

  func fullMul(a, b: uint64; hi: var uint64): uint64 {.inline.} =
    {.cast(noSideEffect).}:
      result = fullMulAsm(a, b, cast[Words](addr hi))
else:
  func fullMul(a, b: uint64; hi: var uint64): uint64 {.inline.} =
    result = fullMulPortable(a, b, hi)

func power(q: int): int =
  ## ⌊q * log2(10)⌋ + 63, as ⌊q * 217706 / 2^16⌋ + 63 — exact over the whole
  ## range of decimal exponents that reach Eisel–Lemire.
  result = int(ashr(int64(q) * 217706'i64, 16)) + 63

func computeProductApprox(q: int; w: uint64; precision: int; lo, hi: var uint64)
    {.requires: SmallestPowerOfFive <= q and q <= LargestPowerOfFive.} =
  ## Approximates w * 5^q in 128 bits. One multiplication is enough unless the
  ## bits below the `precision` we need are all ones, in which case the lower
  ## word of the power decides whether they carry.
  let mask = if precision < 64: 0xFFFFFFFFFFFFFFFF'u64 shr precision
             else: 0xFFFFFFFFFFFFFFFF'u64
  let index = 2 * (q - SmallestPowerOfFive)
  {.assume: index + 1 < PowerOfFive128.len.}
  var firstHi = 0'u64
  var firstLo = fullMul(w, PowerOfFive128[index], firstHi)
  if (firstHi and mask) == mask:
    var secondHi = 0'u64
    discard fullMul(w, PowerOfFive128[index + 1], secondHi)
    firstLo = firstLo + secondHi
    if secondHi > firstLo: firstHi = firstHi + 1'u64
  lo = firstLo
  hi = firstHi

func computeFloat(q: int; w: uint64; f: FloatFormat): BiasedFp =
  ## w * 10^q, correctly rounded, or `p = -1` when 128 bits could not decide.
  if w == 0'u64 or q < f.smallestPowerOfTen:
    result = BiasedFp(m: 0'u64, p: 0)
  elif q > f.largestPowerOfTen:
    result = BiasedFp(m: 0'u64, p: f.infinitePower)
  else:
    let lz = leadingZeros(w)
    var lo = 0'u64
    var hi = 0'u64
    # Both formats' decimal exponent ranges lie inside the table.
    {.assume: SmallestPowerOfFive <= q and q <= LargestPowerOfFive.}
    computeProductApprox(q, w shl lz, f.sigBits + 3, lo, hi)
    # All ones in the low word: the truncated power may be off by one unit,
    # which can only be ignored where 5^q is exact in 128 bits.
    if lo == 0xFFFFFFFFFFFFFFFF'u64 and (q < -27 or q > 55):
      result = BiasedFp(m: 0'u64, p: -1)
    else:
      let upperbit = int(hi shr 63)
      let drop = upperbit + 64 - f.sigBits - 3
      var mantissa = hi shr drop
      var power2 = power(q) + upperbit - lz - f.expMin + 1
      if power2 <= 0:
        # Subnormal (or zero): shift the extra bits out, then round to even.
        if -power2 + 1 >= 64:
          result = BiasedFp(m: 0'u64, p: 0)
        else:
          mantissa = mantissa shr (-power2 + 1)
          mantissa = mantissa + (mantissa and 1'u64)
          mantissa = mantissa shr 1
          # Rounding may have carried into the smallest normal.
          result = BiasedFp(m: mantissa,
            p: (if mantissa >= (1'u64 shl f.sigBits): 1 else: 0))
      else:
        # An exact tie between two floats is only visible when the product is
        # exact (5^q fits in 64 bits) and nothing below the round bit is set;
        # clearing the round bit then rounds down to even instead of up.
        if lo <= 1'u64 and q >= f.minExpRoundToEven and
            q <= f.maxExpRoundToEven and (mantissa and 3'u64) == 1'u64 and
            (mantissa shl drop) == hi:
          mantissa = mantissa and not 1'u64
        mantissa = mantissa + (mantissa and 1'u64)
        mantissa = mantissa shr 1
        if mantissa >= (2'u64 shl f.sigBits):
          # The carry made a new leading bit.
          mantissa = 1'u64 shl f.sigBits
          inc power2
        mantissa = mantissa and not (1'u64 shl f.sigBits)
        if power2 >= f.infinitePower:
          result = BiasedFp(m: 0'u64, p: f.infinitePower)
        else:
          result = BiasedFp(m: mantissa, p: power2)

# ── Simple Decimal Conversion (the slow path) ─────────────────────────────

func trim(d: var DecimalSeq) =
  while d.numDigits > 0 and d.digits[d.numDigits - 1] == 0'u8:
    dec d.numDigits

func round(d: DecimalSeq): uint64 =
  ## The integer part, rounded half to even.
  if d.numDigits == 0 or d.decimalPoint < 0:
    result = 0'u64
  elif d.decimalPoint >= MaxDigitsWithoutOverflow:
    result = 0xFFFFFFFFFFFFFFFF'u64
  else:
    let dp = d.decimalPoint
    result = 0'u64
    for i in 0 ..< dp:
      result = result * 10'u64
      if i < d.numDigits: result = result + uint64(d.digits[i])
    var roundUp = false
    if dp < d.numDigits:
      roundUp = d.digits[dp] >= 5'u8
      if d.digits[dp] == 5'u8 and dp + 1 == d.numDigits:
        # Exactly halfway, unless digits were lost: those make it above.
        roundUp = d.truncated or (dp != 0 and (d.digits[dp - 1] and 1'u8) != 0'u8)
    if roundUp: result = result + 1'u64

func numberOfDigitsLeftShift(d: DecimalSeq; shift: int): int =
  ## How many digits `leftShift(shift)` adds: the digit count of 2^shift, or
  ## one less when the digits compare below 5^shift.
  let s = shift and 63
  let xa = int(LeftShiftTable[s])
  let xb = int(LeftShiftTable[s + 1])
  result = xa shr 11
  let pow5a = xa and 0x7FF
  let pow5b = xb and 0x7FF
  var i = 0
  var decided = false
  while not decided and i < pow5b - pow5a:
    # the table's offsets are increasing and end at its length
    let at = pow5a + i
    {.assume: 0 <= at and at < LeftShiftPow5.len.}
    let p5 = LeftShiftPow5[at]
    if i >= d.numDigits:
      dec result
      decided = true
    elif d.digits[i] != p5:
      if d.digits[i] < p5: dec result
      decided = true
    inc i

func leftShift(d: var DecimalSeq; shift: int) =
  ## d = d * 2^shift, for shift <= 60.
  if d.numDigits > 0:
    let numNewDigits = numberOfDigitsLeftShift(d, shift)
    var readIndex = d.numDigits
    var writeIndex = d.numDigits + numNewDigits
    var n = 0'u64
    while readIndex > 0:
      dec readIndex
      dec writeIndex
      # `writeIndex` stays `numNewDigits` ahead of `readIndex`
      {.assume: 0 <= writeIndex.}
      n = n + (uint64(d.digits[readIndex]) shl shift)
      let quotient = n div 10'u64
      let remainder = n - 10'u64 * quotient
      if writeIndex < MaxDigits: d.digits[writeIndex] = uint8(remainder)
      elif remainder > 0'u64: d.truncated = true
      n = quotient
    while n > 0'u64:
      dec writeIndex
      # `numNewDigits` counts these leading digits too
      {.assume: 0 <= writeIndex.}
      let quotient = n div 10'u64
      let remainder = n - 10'u64 * quotient
      if writeIndex < MaxDigits: d.digits[writeIndex] = uint8(remainder)
      elif remainder > 0'u64: d.truncated = true
      n = quotient
    let total = d.numDigits + numNewDigits
    {.assume: 0 <= total.}
    if total > MaxDigits: d.numDigits = MaxDigits
    else: d.numDigits = total
    d.decimalPoint = d.decimalPoint + numNewDigits
    trim(d)

func rightShift(d: var DecimalSeq; shift: int) =
  ## d = d / 2^shift, for shift <= 60.
  var readIndex = 0
  var writeIndex = 0
  var n = 0'u64
  var empty = false
  # Pick up enough leading digits to produce the first output digit.
  while not empty and (n shr shift) == 0'u64:
    if readIndex < d.numDigits:
      n = 10'u64 * n + uint64(d.digits[readIndex])
      inc readIndex
    elif n == 0'u64:
      empty = true
    else:
      while (n shr shift) == 0'u64:
        n = n * 10'u64
        inc readIndex
  if not empty:
    d.decimalPoint = d.decimalPoint - (readIndex - 1)
    if d.decimalPoint < -DecimalPointRange:
      d.numDigits = 0
      d.decimalPoint = 0
      d.truncated = false
    else:
      let mask = (1'u64 shl shift) - 1'u64
      while readIndex < d.numDigits:
        let newDigit = uint8(n shr shift)
        n = 10'u64 * (n and mask) + uint64(d.digits[readIndex])
        inc readIndex
        # every digit read produces at most one written, and at least one was
        # read before the first write
        {.assume: writeIndex < readIndex.}
        d.digits[writeIndex] = newDigit
        inc writeIndex
      while n > 0'u64:
        let newDigit = uint8(n shr shift)
        n = 10'u64 * (n and mask)
        if writeIndex < MaxDigits:
          d.digits[writeIndex] = newDigit
          inc writeIndex
        elif newDigit > 0'u8:
          d.truncated = true
      {.assume: 0 <= writeIndex and writeIndex <= MaxDigits.}
      d.numDigits = writeIndex
      trim(d)

func parseDecimalSeq(s: openArray[char]; n: Number; d: var DecimalSeq) =
  ## Rereads the digit text `scanNumber` delimited, exactly.
  var inFraction = false
  var nd = 0          # significant digits seen, stored or not
  var dp = 0
  for i in n.digitsStart ..< n.digitsEnd:
    # `scanNumber` delimited the digits inside `s`
    {.assume: 0 <= i and i < s.len.}
    let c = s[i]
    if c == '.':
      inFraction = true
    elif isDigit(c):
      let dig = uint8(ord(c) - ord('0'))
      if nd == 0 and dig == 0'u8:
        if inFraction: dec dp     # a leading zero after the point
      else:
        if nd < MaxDigits: d.digits[nd] = dig
        elif dig != 0'u8: d.truncated = true
        inc nd
        if not inFraction: inc dp
  if nd > MaxDigits: d.numDigits = MaxDigits
  else: d.numDigits = nd
  d.decimalPoint = dp + n.explicitExp
  trim(d)
  if d.numDigits == 0: d.decimalPoint = 0

func parseLongMantissa(s: openArray[char]; n: Number; f: FloatFormat): BiasedFp =
  ## Scale the exact decimal by powers of two until it lies in [1/2, 1), move
  ## the binary point past the significand bits and round once.
  const
    MaxShift = 60
    Powers = [0, 3, 6, 9, 13, 16, 19, 23, 26, 29, 33, 36, 39, 43, 46, 49, 53, 56, 59]
  let fpZero = BiasedFp(m: 0'u64, p: 0)
  let fpInf = BiasedFp(m: 0'u64, p: f.infinitePower)
  var d = DecimalSeq(numDigits: 0, decimalPoint: 0, truncated: false)
  parseDecimalSeq(s, n, d)
  result = fpZero
  if d.numDigits == 0 or d.decimalPoint < -324:
    discard
  elif d.decimalPoint >= 310:
    result = fpInf
  else:
    var exp2 = 0
    var done = false
    # Shift right toward [1/2, 1).
    while not done and d.decimalPoint > 0:
      let shift = if d.decimalPoint < Powers.len: Powers[d.decimalPoint] else: MaxShift
      rightShift(d, shift)
      if d.decimalPoint < -DecimalPointRange:
        result = fpZero
        done = true
      exp2 = exp2 + shift
    # Shift left toward [1/2, 1).
    while not done and d.decimalPoint <= 0:
      var shift = 0
      if d.decimalPoint == 0:
        if d.digits[0] >= 5'u8: break
        shift = if d.digits[0] < 2'u8: 2 else: 1
      else:
        let k = -d.decimalPoint
        {.assume: 0 < k.}
        shift = if k < Powers.len: Powers[k] else: MaxShift
      leftShift(d, shift)
      if d.decimalPoint > DecimalPointRange:
        result = fpInf
        done = true
      exp2 = exp2 - shift
    if not done:
      # [1/2, 1) here, but the binary format normalizes to [1, 2).
      dec exp2
      while f.expMin > exp2:
        let shift = min(f.expMin - exp2, MaxShift)
        rightShift(d, shift)
        exp2 = exp2 + shift
      if exp2 - f.expMin + 1 >= f.infinitePower:
        result = fpInf
      else:
        # Move the hidden bit to the units place and round.
        leftShift(d, f.sigBits + 1)
        var mantissa = round(d)
        if mantissa >= (1'u64 shl (f.sigBits + 1)):
          # Rounding carried into a new leading bit.
          rightShift(d, 1)
          inc exp2
          mantissa = round(d)
        if exp2 - f.expMin + 1 >= f.infinitePower:
          result = fpInf
        else:
          var power2 = exp2 - f.expMin + 1
          if mantissa < (1'u64 shl f.sigBits): dec power2   # subnormal
          result = BiasedFp(m: mantissa and ((1'u64 shl f.sigBits) - 1'u64),
                            p: power2)

# ── putting it together ───────────────────────────────────────────────────

func decimalToBits(s: openArray[char]; n: Number; f: FloatFormat): uint64 =
  ## The bits of |value| for the formats Clinger's fast path cannot do.
  var fp = computeFloat(n.exponent, n.mantissa, f)
  if n.manyDigits and fp.p >= 0:
    # Dropped digits put the value in (mantissa, mantissa+1) * 10^exponent;
    # if both ends round alike, so does everything between.
    let up = computeFloat(n.exponent, n.mantissa + 1'u64, f)
    if up.m != fp.m or up.p != fp.p: fp.p = -1
  if fp.p < 0:
    fp = parseLongMantissa(s, n, f)
  result = fp.m or (uint64(fp.p) shl f.sigBits)

func fastPath64(n: Number; value: var float64): bool =
  ## Clinger: exact operands, so the one IEEE operation rounds correctly.
  ## Not on i386, where C compilers default to the x87 FPU: it computes in
  ## 80-bit registers and rounds a second time when storing the double, which
  ## can be off by one ulp. Eisel–Lemire, integer-only, takes those instead.
  ## (`fastPath32` is fine there: 64 significand bits >= 2*24+2 make the
  ## double rounding harmless for one float32 operation.)
  result = false
  if not defined(i386) and not n.manyDigits and n.mantissa <= MaxMantissaFastPath64 and
      -MaxExpFastPath64 <= n.exponent and n.exponent <= MaxExpDisguised64:
    if n.exponent < 0:
      value = float64(n.mantissa) / Pow10F64[-n.exponent]
      result = true
    elif n.exponent <= MaxExpFastPath64:
      value = float64(n.mantissa) * Pow10F64[n.exponent]
      result = true
    else:
      # Disguised: 123e30 is 123000000000000e22.
      let pow = IntPow10[n.exponent - MaxExpFastPath64]
      if n.mantissa <= MaxMantissaFastPath64 div pow:
        value = float64(n.mantissa * pow) * Pow10F64[MaxExpFastPath64]
        result = true

func fastPath32(n: Number; value: var float32): bool =
  result = false
  if not n.manyDigits and n.mantissa <= MaxMantissaFastPath32 and
      -MaxExpFastPath32 <= n.exponent and n.exponent <= MaxExpDisguised32:
    if n.exponent < 0:
      value = float32(n.mantissa) / Pow10F32[-n.exponent]
      result = true
    elif n.exponent <= MaxExpFastPath32:
      value = float32(n.mantissa) * Pow10F32[n.exponent]
      result = true
    else:
      let pow = IntPow10[n.exponent - MaxExpFastPath32]
      if n.mantissa <= MaxMantissaFastPath32 div pow:
        value = float32(n.mantissa * pow) * Pow10F32[MaxExpFastPath32]
        result = true

func parseFloat64*(s: openArray[char]; number: var float64): int =
  ## Reads a decimal float at the start of `s` into `number`, correctly
  ## rounded to nearest, ties to even. Returns the number of characters read,
  ## or 0 (leaving `number` alone) if `s` does not start with a float.
  var n = Number(mantissa: 0'u64, exponent: 0, negative: false,
                 manyDigits: false, digitsStart: 0, digitsEnd: 0, explicitExp: 0)
  result = scanNumber(s, n)
  if result > 0:
    var value = 0.0
    if not fastPath64(n, value):
      value = cast[float64](decimalToBits(s, n, F64))
    number = if n.negative: -value else: value
  else:
    # Only text without digits can be a special value.
    var isNan = false
    var negative = false
    result = scanSpecial(s, isNan, negative)
    if result > 0:
      if isNan: number = NaN
      elif negative: number = -Inf
      else: number = Inf

func parseFloat32*(s: openArray[char]; number: var float32): int =
  ## Like `parseFloat64`, rounding once, directly to binary32 — never via a
  ## float64, which would round twice.
  var n = Number(mantissa: 0'u64, exponent: 0, negative: false,
                 manyDigits: false, digitsStart: 0, digitsEnd: 0, explicitExp: 0)
  result = scanNumber(s, n)
  if result > 0:
    var value = 0.0'f32
    if not fastPath32(n, value):
      value = cast[float32](uint32(decimalToBits(s, n, F32)))
    number = if n.negative: -value else: value
  else:
    var isNan = false
    var negative = false
    result = scanSpecial(s, isNan, negative)
    if result > 0:
      if isNan: number = float32(NaN)
      elif negative: number = float32(-Inf)
      else: number = float32(Inf)
