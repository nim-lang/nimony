# Generates all Unicode data tables of `std/unicode` and the
# NormalizationTest subset that checks them, from one Unicode version.
#
# Usage (Nim 2):
#
#   nim c -r tools/gen_unicode.nim <ucd-dir>
#
# `<ucd-dir>` holds `UnicodeData.txt` and `NormalizationTest.txt` of one
# Unicode version, downloaded from https://www.unicode.org/Public/<version>/ucd/.
# The raw files are not checked in. Output:
#
# - `lib/std/includes/unicode_ranges.nim`: simple case mappings (fields
#   12-14 of UnicodeData.txt, for every code point that has one, letters
#   or not), the letters (category L) and the white space (category Z
#   plus a few controls). Ported from Nim's tools/unicode_parsedata.nim,
#   which only took the case mappings of letters.
# - `lib/std/includes/unicode_normdata.nim`: decompositions, canonical
#   combining classes and the mark categories (M and Mn).
# - `tests/nimony/stdlib/tunicode_normtest.nim`: a subset of
#   NormalizationTest.txt (Part0 and Part3 whole, Part1 for Latin, Greek,
#   Cyrillic and Arabic plus a sample of the rest, a sample of Part2).
#
# Last run with Unicode 16.0.0.

import std / [strutils, os, algorithm]

const
  rangesOut = "lib/std/includes/unicode_ranges.nim"
  libOut = "lib/std/includes/unicode_normdata.nim"
  testOut = "tests/nimony/stdlib/tunicode_normtest.nim"

type
  Decomp = object
    code: int
    compat: bool
    mapping: seq[int]

  Range = tuple[first, last, value: int]

proc parseCodes(s: string): seq[int] =
  for x in s.splitWhitespace: result.add parseHexInt(x)

proc readUnicodeData(path: string; decomps: var seq[Decomp];
                     ccc: var seq[Range]; marks, nonspacing: var seq[Range]) =
  ## Reads the fields this module needs. `First>`/`Last>` pairs denote
  ## ranges; none of them has a decomposition, a mark category or a
  ## non-zero combining class, which the asserts below check.
  var rangeFirst = -1
  for line in lines(path):
    if line.len == 0: continue
    let f = line.split(';')
    let code = parseHexInt(f[0])
    var first = code
    if f[1].endsWith(", First>"):
      rangeFirst = code
      continue
    if f[1].endsWith(", Last>"):
      first = rangeFirst
      doAssert f[5] == "" and f[3] == "0" and f[2][0] != 'M', line
    let category = f[2]
    let cls = parseInt(f[3])
    if cls != 0:
      ccc.add (first, code, cls)
    if category in ["Mn", "Mc", "Me"]:
      marks.add (first, code, 1)
    if category == "Mn":
      nonspacing.add (first, code, 1)
    if f[5].len > 0:
      var d = Decomp(code: code, compat: f[5][0] == '<')
      let codes = if d.compat: f[5].split("> ", 1)[1] else: f[5]
      d.mapping = parseCodes(codes)
      decomps.add d

proc merge(a: seq[Range]): seq[Range] =
  ## Joins adjacent ranges with the same value.
  for r in a:
    if result.len > 0 and result[^1].last + 1 == r.first and
        result[^1].value == r.value:
      result[^1].last = r.last
    else:
      result.add r

proc hex(x: int): string = "0x" & toHex(x, 5)

proc emitArray(o: var string; name, doc: string; items: seq[string]; perLine: int) =
  ## `name = [...]` of int32: the first item carries the type suffix.
  o.add "  " & name & " = [\n" & doc
  for i, x in items:
    if i mod perLine == 0: o.add "    "
    if i == 0:
      let comma = x.find(',')
      o.add(if comma < 0: x & "'i32" else: x[0 ..< comma] & "'i32" & x[comma .. ^1])
    else:
      o.add x
    o.add(if i mod perLine == perLine - 1 or i == items.len - 1: ",\n" else: ", ")
  o.add "  ]\n\n"

proc emitRanges(o: var string; name, doc: string; a: seq[Range]; withValue: bool) =
  var items: seq[string]
  for r in a:
    var item = hex(r.first) & ", " & hex(r.last)
    if withValue: item.add ", " & $r.value
    items.add item
  emitArray(o, name, "    # " & doc & "\n", items, 4)

proc genLib(version: string; decomps: seq[Decomp];
            ccc, marks, nonspacing: seq[Range]): string =
  var maxLen = 0
  for d in decomps: maxLen = max(maxLen, d.mapping.len)
  doAssert maxLen < 32
  result = "# Generated by tools/gen_unicode.nim from UnicodeData.txt " &
    version & ". DO NOT EDIT!\n\n"
  result.add "const\n"
  result.add "  normDataVersion = \"" & version & "\"\n\n"
  var data: seq[int]
  var items, dataItems: seq[string]
  for d in decomps:
    let packed = (data.len shl 6) or (d.mapping.len shl 1) or ord(d.compat)
    items.add hex(d.code) & ", " & $packed
    data.add d.mapping
  for x in data: dataItems.add hex(x)
  emitArray(result, "decompositions",
    "    # code point, (offset shl 6) or (length shl 1) or compat: the single-level\n" &
    "    # mapping of UnicodeData.txt field 5, stored in `decompData`; compat is 1\n" &
    "    # for a compatibility mapping. Hangul syllables are algorithmic.\n",
    items, 4)
  emitArray(result, "decompData", "", dataItems, 8)
  emitRanges(result, "combiningClassRanges",
    "first, last, canonical combining class (non-zero only)", merge(ccc), true)
  emitRanges(result, "markRanges",
    "first, last: general category M (Mn, Mc, Me)", merge(marks), false)
  emitRanges(result, "nonspacingMarkRanges",
    "first, last: general category Mn", merge(nonspacing), false)

# --- Case mappings, letters and white space (unicode_ranges.nim) ---

type
  Mapping = tuple[code, diff: int]   # diff = 500 + mapped - code
  CaseRange = tuple[first, last, diff: int]
  CodeRange = tuple[first, last: int]

  CaseData = object
    toUpper, toLower, toTitle: seq[Mapping]
    alphas, spaces: seq[int]

proc readCaseData(path: string): CaseData =
  ## Simple case mappings are taken for every code point that has one,
  ## whatever its category: besides letters, U+0345 (Mn), the Roman
  ## numerals (Nl) and the circled letters (So) have them. `toTitle` only
  ## keeps the code points whose title case differs from their upper case
  ## (`toTitle` falls back to `toUpper`); a title case equal to the code
  ## point itself is kept too.
  result = CaseData()
  var rangeFirst = -1
  for line in lines(path):
    if line.len == 0: continue
    let f = line.split(';')
    let code = parseHexInt(f[0])
    var first = code
    if f[1].endsWith(", First>"):
      rangeFirst = code
      continue
    if f[1].endsWith(", Last>"):
      first = rangeFirst
      doAssert f[12] == "" and f[13] == "" and f[14] == "", line
    let category = f[2]
    let (uc, lc, tc) = (f[12], f[13], f[14])
    # UAX #44: an empty title case field means "same as upper case";
    # UnicodeData.txt always fills it when the upper case field is set.
    doAssert uc == "" or tc != "", line
    if uc.len > 0: result.toUpper.add (code, 500 + parseHexInt(uc) - code)
    if lc.len > 0: result.toLower.add (code, 500 + parseHexInt(lc) - code)
    if tc != uc: result.toTitle.add (code, 500 + parseHexInt(tc) - code)
    for c in first .. code:
      if category[0] == 'L':
        result.alphas.add c
      elif category in ["Zs", "Zl", "Zp"]:
        result.spaces.add c
  # Not category Z, but white space all the same: \t, \n, \v, \f, \r, NEL.
  for c in 0x09 .. 0x0D: result.spaces.add c
  result.spaces.add 0x85
  result.spaces.sort()

proc splitRanges(a: seq[Mapping]; r: var seq[CaseRange]; s: var seq[Mapping]) =
  ## Runs of at least two consecutive code points with the same `diff` go
  ## to `r`, the rest to `s`.
  var i = 0
  while i < a.len:
    var j = i + 1
    while j < a.len and a[j].code == a[j-1].code + 1 and a[j].diff == a[i].diff:
      inc j
    if j - i == 1: s.add a[i]
    else: r.add (a[i].code, a[j-1].code, a[i].diff)
    i = j

proc splitRanges(a: seq[int]; r: var seq[CodeRange]; s: var seq[int]) =
  var i = 0
  while i < a.len:
    var j = i + 1
    while j < a.len and a[j] == a[j-1] + 1: inc j
    if j - i == 1: s.add a[i]
    else: r.add (a[i], a[j-1])
    i = j

proc genRanges(version: string; d: CaseData): string =
  var lowerR, upperR, titleR: seq[CaseRange]
  var lowerS, upperS, titleS: seq[Mapping]
  var alphaR, spaceR, spaceS: seq[CodeRange]
  var alphaS, spaceSingle: seq[int]
  splitRanges(d.toLower, lowerR, lowerS)
  splitRanges(d.toUpper, upperR, upperS)
  splitRanges(d.alphas, alphaR, alphaS)
  # `isWhiteSpace` searches ranges only: every space is in a range, single
  # code points included.
  splitRanges(d.spaces, spaceR, spaceSingle)
  for c in spaceSingle: spaceR.add (c, c)
  spaceR.sort(proc (a, b: CodeRange): int = cmp(a.first, b.first))
  result = "# Generated by tools/gen_unicode.nim from UnicodeData.txt " &
    version & ". DO NOT EDIT!\n\n"
  result.add "const\n"
  result.add "  caseDataVersion = \"" & version & "\"\n\n"
  proc caseRanges(o: var string; name, doc: string; a: seq[CaseRange]) =
    var items: seq[string]
    for r in a: items.add hex(r.first) & ", " & hex(r.last) & ", " & $r.diff
    emitArray(o, name, "    # " & doc & "\n", items, 1)
  proc caseSinglets(o: var string; name, doc: string; a: seq[Mapping]) =
    var items: seq[string]
    for r in a: items.add hex(r.code) & ", " & $r.diff
    emitArray(o, name, "    # " & doc & "\n", items, 1)
  const rdoc = "first, last, 500 + mapped - code (the same for the whole run)"
  const sdoc = "code point, 500 + mapped - code"
  caseRanges(result, "toLowerRanges", rdoc, lowerR)
  caseSinglets(result, "toLowerSinglets", sdoc, lowerS)
  caseRanges(result, "toUpperRanges", rdoc, upperR)
  caseSinglets(result, "toUpperSinglets", sdoc, upperS)
  caseSinglets(result, "toTitleSinglets",
    sdoc & ", where title case differs from upper case", d.toTitle)
  var items: seq[string]
  for r in alphaR: items.add hex(r.first) & ", " & hex(r.last)
  emitArray(result, "alphaRanges", "    # first, last: general category L\n", items, 1)
  items = @[]
  for c in alphaS: items.add hex(c)
  emitArray(result, "alphaSinglets", "    # general category L\n", items, 1)
  items = @[]
  for r in spaceR: items.add hex(r.first) & ", " & hex(r.last)
  emitArray(result, "spaceRanges",
    "    # first, last: general category Z and U+0009..U+000D, U+0085\n", items, 1)
  result.add "  unicodeSpaces = [\n"
  for c in d.spaces: result.add "    Rune " & hex(c) & ",\n"
  result.add "  ]\n"

# --- NormalizationTest subset ---

proc inSampledBlock(c: int): bool =
  c in 0x00C0..0x024F or c in 0x1E00..0x1EFF or # Latin
    c in 0x0370..0x03FF or c in 0x1F00..0x1FFF or # Greek
    c in 0x0400..0x04FF or # Cyrillic
    c in 0x0600..0x06FF # Arabic

proc genTests(version, path: string): tuple[src: string, count: int] =
  var part = ""
  var lineNo = 0
  var picked: seq[string]
  for line in lines(path):
    if line.startsWith("@Part"):
      part = line[0 .. 5]
      lineNo = 0
      continue
    if line.len == 0 or line[0] == '#': continue
    inc lineNo
    let fields = line.split(" #", 1)[0].split(';')
    let c1 = parseCodes(fields[0])
    let keep = case part
      of "@Part0", "@Part3": true
      of "@Part1": inSampledBlock(c1[0]) or
                   (c1[0] in 0xFB50..0xFEFF and lineNo mod 8 == 0) or
                   lineNo mod 80 == 0
      of "@Part2": lineNo mod 20 == 0
      else: false
    if keep: picked.add fields[0 .. 4].join(";")
  var o = "# Generated by tools/gen_unicode.nim from NormalizationTest.txt " &
    version & ". DO NOT EDIT!\n"
  o.add """# A subset of Unicode's conformance test: for every line c1;c2;c3;c4;c5
#   c3 == toNFD(c1) == toNFD(c2) == toNFD(c3)
#   c5 == toNFD(c4) == toNFD(c5)
#   c5 == toNFKD(c1) == ... == toNFKD(c5)
import std/[assertions, parseutils, syncio, unicode]

const cases = [
"""
  for p in picked: o.add "  \"" & p & "\",\n"
  o.add """]

proc decode(field: string): string =
  ## "0044 0307" -> "Ḋ"
  result = ""
  var i = 0
  while i < field.len:
    if field[i] == ' ':
      inc i
    else:
      var code = 0
      let n = parseHex(field, code, i)
      assert n > 0
      result.add Rune(code)
      inc i, n

proc fields(line: string): array[5, string] =
  result = default(array[5, string])
  var k = 0
  var start = 0
  for i in 0 .. line.len:
    if i == line.len or line[i] == ';':
      result[k] = decode(line.substr(start, i - 1))
      inc k
      start = i + 1
  assert k == 5

var checked = 0
for line in cases:
  let c = fields(line)
  for i in 0 .. 2:
    assert toNFD(c[i]) == c[2], line
  for i in 3 .. 4:
    assert toNFD(c[i]) == c[4], line
  for i in 0 .. 4:
    assert toNFKD(c[i]) == c[4], line
  inc checked
echo checked, " NormalizationTest lines passed"
"""
  result = (o, picked.len)

proc main =
  if paramCount() != 1:
    quit "usage: gen_unicode <ucd-dir>"
  let dir = paramStr(1)
  let header = readFile(dir / "NormalizationTest.txt").splitLines()[0]
  # "# NormalizationTest-16.0.0.txt"
  let version = header.split('-', 1)[1].replace(".txt", "")
  var decomps: seq[Decomp]
  var ccc, marks, nonspacing: seq[Range]
  readUnicodeData(dir / "UnicodeData.txt", decomps, ccc, marks, nonspacing)
  let caseData = readCaseData(dir / "UnicodeData.txt")
  writeFile(rangesOut, genRanges(version, caseData))
  doAssert decomps.isSorted(proc (a, b: Decomp): int = cmp(a.code, b.code))
  writeFile(libOut, genLib(version, decomps, ccc, marks, nonspacing))
  let (src, count) = genTests(version, dir / "NormalizationTest.txt")
  writeFile(testOut, src)
  echo "Unicode ", version, ": ", caseData.toLower.len, " lower, ",
    caseData.toUpper.len, " upper, ", caseData.toTitle.len, " title mappings, ",
    caseData.alphas.len, " letters, ", caseData.spaces.len, " spaces; ",
    decomps.len, " decompositions, ",
    merge(ccc).len, " combining class ranges, ", merge(marks).len,
    " mark ranges, ", merge(nonspacing).len, " Mn ranges; ", count, " test lines"

main()
