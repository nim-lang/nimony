#!/usr/bin/env python3
# Generates the vector files of trsasign.nim (not run by the suite).
#
#   python3 -P rsasign_vectors.py WYCHEPROOF_DIR NIST_DIR KEYDIR OUTDIR
#
# WYCHEPROOF_DIR: files of https://github.com/C2SP/wycheproof testvectors_v1/
#   rsa_pkcs1_{2048,3072,4096}_sig_gen_test.json and
#   rsa_signature_{2048,3072,4096}_sha256_test.json (Apache License 2.0).
# NIST_DIR: SigGen15_186-3.txt from NIST CAVP's 186-3rsatestvectors.zip
#   (https://csrc.nist.gov/CSRC/media/Projects/Cryptographic-Algorithm-Validation-Program/documents/dss/186-3rsatestvectors.zip;
#   a work of the US government, not subject to copyright in the US).
# KEYDIR: tests/nimony/crypto/rsakeys (throwaway openssl keys).
#
# Writes OUTDIR/wycheproof_siggen.txt, nist_siggen15.txt,
# wycheproof_messages.txt and openssl.txt. Every expected signature is
# checked against Python `cryptography` (OpenSSL-backed) before it is written.
import json
import os
import subprocess
import sys

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import padding, rsa

HASHES = {"SHA-256": ("256", hashes.SHA256()), "SHA-384": ("384", hashes.SHA384()),
          "SHA-512": ("512", hashes.SHA512())}
wdir, ndir, keydir, out = sys.argv[1:5]


def hexs(b):
    return b.hex() if b else "-"


def check(key, msg, sig, h):
    got = key.sign(msg, padding.PKCS1v15(), h)
    assert got == sig, "reference mismatch"


def wycheproof_siggen():
    lines = ["# Wycheproof (https://github.com/C2SP/wycheproof, Apache License 2.0,",
             "# Copyright Google LLC), testvectors_v1/rsa_pkcs1_{2048,3072,4096}_sig_gen_test.json:",
             "# every SHA-256/384/512 group. `key` is the group's privateKeyPkcs8 (DER),",
             "# `t hash tcId msg sig` a test (`-` for an empty message). Generated by",
             "# rsasign_vectors.py; do not edit."]
    count = 0
    for bits in (2048, 3072, 4096):
        d = json.load(open(os.path.join(wdir, f"rsa_pkcs1_{bits}_sig_gen_test.json")))
        for g in d["testGroups"]:
            if g["sha"] not in HASHES:
                continue
            name, h = HASHES[g["sha"]]
            der = bytes.fromhex(g["privateKeyPkcs8"])
            key = serialization.load_der_private_key(der, None)
            lines.append("key " + der.hex())
            for t in g["tests"]:
                msg, sig = bytes.fromhex(t["msg"]), bytes.fromhex(t["sig"])
                assert t["result"] in ("valid", "acceptable")
                check(key, msg, sig, h)
                lines.append(f"t {name} {t['tcId']} {hexs(msg)} {sig.hex()}")
                count += 1
    write("wycheproof_siggen.txt", lines)
    return count


def recover(n, e, d):
    p, q = rsa.rsa_recover_prime_factors(n, e, d)
    if p < q:
        p, q = q, p
    priv = rsa.RSAPrivateNumbers(p, q, d, rsa.rsa_crt_dmp1(d, p), rsa.rsa_crt_dmq1(d, q),
                                 rsa.rsa_crt_iqmp(p, q), rsa.RSAPublicNumbers(e, n))
    return priv.private_key()


def nist_siggen():
    lines = ["# NIST CAVP SigGen15_186-3.txt (186-3rsatestvectors.zip, a work of the US",
             "# government): RSASSA-PKCS1-v1_5 with SHA-256/384/512. The file gives n, e",
             "# and d; p and q were recovered from them (SP 800-56B, Appendix C) to write",
             "# `key`, a PKCS #1 RSAPrivateKey (DER). `t hash index msg sig`.",
             "# Generated by rsasign_vectors.py; do not edit."]
    count = 0
    n = e = key = None
    sha = msg = None
    idx = 0
    for raw in open(os.path.join(ndir, "SigGen15_186-3.txt")):
        line = raw.strip()
        if "=" not in line or line.startswith("#") or line.startswith("["):
            continue
        k, v = (x.strip() for x in line.split("=", 1))
        if k == "n":
            n, key = int(v, 16), None
        elif k == "e":
            e = int(v, 16)
        elif k == "d":
            key = recover(n, e, int(v, 16))
            der = key.private_bytes(serialization.Encoding.DER,
                                    serialization.PrivateFormat.TraditionalOpenSSL,
                                    serialization.NoEncryption())
            lines.append("key " + der.hex())
        elif k == "SHAAlg":
            sha = v
        elif k == "Msg":
            msg = bytes.fromhex(v)
        elif k == "S":
            hname = "SHA-" + sha[3:]
            idx += 1
            if hname not in HASHES:
                continue
            name, h = HASHES[hname]
            sig = bytes.fromhex(v)
            check(key, msg, sig, h)
            lines.append(f"t {name} {idx} {hexs(msg)} {sig.hex()}")
            count += 1
    write("nist_siggen15.txt", lines)
    return count


def wycheproof_messages():
    lines = ["# The distinct messages of Wycheproof (https://github.com/C2SP/wycheproof,",
             "# Apache License 2.0, Copyright Google LLC) testvectors_v1/",
             "# rsa_signature_{2048,3072,4096}_sha256_test.json. Those files hold public",
             "# keys only, so trsasign signs each message with the throwaway key of the",
             "# same size and verifies with std/crypto/rsa. `m bits msg`.",
             "# Generated by rsasign_vectors.py; do not edit."]
    count = 0
    for bits in (2048, 3072, 4096):
        d = json.load(open(os.path.join(wdir, f"rsa_signature_{bits}_sha256_test.json")))
        seen = []
        for g in d["testGroups"]:
            for t in g["tests"]:
                if t["msg"] not in seen:
                    seen.append(t["msg"])
        for m in seen:
            lines.append(f"m {bits} {m or '-'}")
            count += 1
    write("wycheproof_messages.txt", lines)
    return count


def b64url(b):
    import base64
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode()


JWT_HEADER = '{"alg":"RS256","typ":"JWT"}'
JWT_CLAIMS = ('{"iss":"nimony-test@example.iam.gserviceaccount.com",'
              '"scope":"https://www.googleapis.com/auth/devstorage.read_only",'
              '"aud":"https://oauth2.googleapis.com/token","exp":1767229200,"iat":1767225600}')


def messages():
    jwt_input = b64url(JWT_HEADER.encode()) + "." + b64url(JWT_CLAIMS.encode())
    return [("empty", b""), ("hello", b"hello nimony"), ("jwt", jwt_input.encode()),
            ("64k", bytes(i % 251 for i in range(65536)))]


def openssl_sigs():
    lines = ["# `openssl dgst -shaN -sign KEY` of the messages of trsasign.nim, made with",
             "# " + subprocess.run(["openssl", "version"], capture_output=True,
                                   text=True).stdout.strip() + ".",
             "# `s key hash message sig`; `j key jwt` is the RS256 JWT of the test's claims.",
             "# Generated by rsasign_vectors.py; do not edit."]
    count = 0
    for keyname, hs in (("test2048", ("256", "384", "512")), ("test2048b", ("256",)),
                        ("test3072", ("256", "384", "512")), ("test4096", ("256", "384", "512"))):
        path = os.path.join(keydir, keyname + ".pkcs8.pem")
        for h in hs:
            for mname, msg in messages():
                sig = subprocess.run(["openssl", "dgst", "-sha" + h, "-sign", path],
                                     input=msg, capture_output=True, check=True).stdout
                lines.append(f"s {keyname} {h} {mname} {sig.hex()}")
                count += 1
                if h == "256" and mname == "jwt":
                    lines.append(f"j {keyname} {msg.decode()}.{b64url(sig)}")
    write("openssl.txt", lines)
    return count


def write(name, lines):
    with open(os.path.join(out, name), "w") as f:
        f.write("\n".join(lines) + "\n")


print("wycheproof siggen", wycheproof_siggen())
print("nist siggen15", nist_siggen())
print("wycheproof messages", wycheproof_messages())
print("openssl", openssl_sigs())
