import std/syncio
import std/crypto/ecdsa

proc hexVal(c: char): int =
  if c in {'0'..'9'}: ord(c) - ord('0')
  elif c in {'a'..'f'}: ord(c) - ord('a') + 10
  else: ord(c) - ord('A') + 10

proc unhex(s: string): seq[byte] =
  result = @[]
  var i = 0
  while i + 1 < s.len:
    result.add byte(hexVal(s[i]) * 16 + hexVal(s[i+1]))
    i += 2

proc check(c: Curve; pub, dig, sig: string) =
  let p = unhex(pub)
  let d = unhex(dig)
  let s = unhex(sig)
  echo ecdsaVerifyDer(c, p, d, s)
  # a flipped digest bit must fail
  var bad = d
  bad[0] = bad[0] xor 1'u8
  echo ecdsaVerifyDer(c, p, bad, s)

