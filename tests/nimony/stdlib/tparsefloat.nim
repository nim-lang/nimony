# Correctly rounded decimal -> float64/float32 (`private/dec2flt`, a port of
# Rust's `core::num::dec2flt`). Every expected bit pattern below was computed
# with exact rational arithmetic, rounding once to nearest, ties to even.

proc bits64(s: string): uint64 =
  var x = 0.0
  assert parseFloat(s, x) == s.len
  result = cast[uint64](x)

proc bits32(s: string): uint32 =
  var x = 0.0'f32
  assert parseFloat(s, x) == s.len
  result = cast[uint32](x)

